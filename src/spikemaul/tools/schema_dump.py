"""Write down what the book looks like, out of the migrations that make it.

The schema document is generated because a hand written one is wrong within a
month and nobody notices until somebody trusts it. It is written into the
checkout and CI checks it is current, so a migration that lands without the
document being regenerated fails the build rather than quietly making the
document a lie.

The dump is taken from a book built by running the migrations, not from
parsing the migration text. That way it says what sqlite actually made, which
is the thing anybody reading the document is asking about.
"""

from __future__ import annotations

import argparse
import sys
from datetime import date
from pathlib import Path

from spikemaul.store.book import new_book
from spikemaul.store.migrations import MIGRATIONS, migrate
from spikemaul.tools.sources import project_root

DOCUMENT = "docs/schema.md"
"""Where the document lives, relative to the checkout."""

BUILT_ON = date(2025, 1, 6)
"""The day the dump says the schema was applied, so the text does not move."""


def dump() -> str:
    """The schema document, as it should be on disk."""
    book = new_book()
    migrate(book, BUILT_ON)
    lines = [
        "# The book",
        "",
        "Generated by `python -m spikemaul.tools.schema_dump`. Do not edit.",
        "",
        f"Schema {max(one.number for one in MIGRATIONS)}, "
        f"{len(MIGRATIONS)} migrations, {len(book.tables)} tables.",
        "",
    ]
    for table in book.tables:
        lines.append(f"## {table}")
        lines.append("")
        rows = book.query(f"PRAGMA table_info({table})")
        lines.append("| column | type | not null | default |")
        lines.append("| --- | --- | --- | --- |")
        for row in rows:
            default = row["dflt_value"]
            lines.append(
                f"| {row['name']} | {row['type']} | "
                f"{'yes' if row['notnull'] else 'no'} | {default if default else ''} |"
            )
        keys = [row["name"] for row in rows if row["pk"]]
        if keys:
            lines.append("")
            lines.append(f"Key: {', '.join(keys)}.")
        lines.append("")
    lines.append("## Migrations")
    lines.append("")
    for one in MIGRATIONS:
        lines.append(f"{one.number}. {one.name}")
    lines.append("")
    book.close()
    return "\n".join(lines)


def where() -> Path:
    """The path the document is written to."""
    return project_root() / DOCUMENT


def write() -> Path:
    """Write the document and say where it went."""
    path = where()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump(), encoding="utf-8")
    return path


def is_current() -> bool:
    """Whether the document on disk is what the migrations would write."""
    path = where()
    return path.exists() and path.read_text(encoding="utf-8") == dump()


def main() -> None:
    """Write the document, or check it is current and exit."""
    parser = argparse.ArgumentParser(description="write the schema document")
    parser.add_argument("--check", action="store_true", help="only say whether it is current")
    if parser.parse_args().check:
        if is_current():
            print(f"{DOCUMENT} is current")
            sys.exit(0)
        print(f"{DOCUMENT} is not what the migrations would write")
        sys.exit(1)
    print(f"wrote {write()}")


if __name__ == "__main__":
    main()
