"""Write the glossary out of the source, so nobody argues about what a word means.

Half the words in this package are terms of art and the other half look like
terms of art and are not. A glossary written by hand disagrees with the code
within a season. This one is generated: every enumeration in the package is a
list of the values the office is allowed to write down, and the docstring
beside each one is what it means.

What it cannot generate is the prose at the top, so that is kept in the tool
and regenerated with the rest.
"""

from __future__ import annotations

import argparse
import ast
import sys
from dataclasses import dataclass
from pathlib import Path

from spikemaul.tools.sources import Problem, module_name, parsed, project_root, source_files

DOCUMENT = "docs/glossary.md"
"""Where the glossary lives, relative to the checkout."""

PREAMBLE = """# Glossary

Generated by `python -m spikemaul.tools.build_glossary`. Do not edit.

Every list below is an enumeration in the source. If a word is not here, the
package does not know it, and a form that offers it is offering something the
book will refuse.
"""


@dataclass(frozen=True)
class Term:
    """One enumeration, where it lives and what it holds."""

    name: str
    module: str
    says: str
    values: tuple[str, ...]


def _is_enum(node: ast.ClassDef) -> bool:
    return any(isinstance(base, ast.Name) and base.id == "Enum" for base in node.bases)


def _values(node: ast.ClassDef) -> tuple[str, ...]:
    out = []
    for statement in node.body:
        if not isinstance(statement, ast.Assign):
            continue
        value = statement.value
        if isinstance(value, ast.Constant) and isinstance(value.value, str):
            out.append(value.value)
    return tuple(out)


def terms() -> list[Term]:
    """Every enumeration in the package, in name order."""
    out = []
    for path in source_files():
        tree = parsed(path)
        for node in tree.body:
            if not isinstance(node, ast.ClassDef) or not _is_enum(node):
                continue
            values = _values(node)
            if not values:
                continue
            says = (ast.get_docstring(node) or "").strip().splitlines()
            out.append(
                Term(
                    name=node.name,
                    module=module_name(path),
                    says=says[0] if says else "",
                    values=values,
                )
            )
    return sorted(out, key=lambda one: one.name)


def build() -> str:
    """The glossary, as it should be on disk."""
    lines = [PREAMBLE.rstrip(), ""]
    for term in terms():
        lines.append(f"## {term.name}")
        lines.append("")
        if term.says:
            lines.append(term.says)
            lines.append("")
        lines.append(f"From `{term.module}`.")
        lines.append("")
        for value in term.values:
            lines.append(f"- {value}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def where() -> Path:
    """The path the glossary is written to."""
    return project_root() / DOCUMENT


def write() -> Path:
    """Write the glossary and say where it went."""
    path = where()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build(), encoding="utf-8")
    return path


def is_current() -> bool:
    """Whether the glossary on disk is what the source would write."""
    path = where()
    return path.exists() and path.read_text(encoding="utf-8") == build()


def problems() -> list[Problem]:
    """The one thing this can find, which is that the document is stale."""
    if is_current():
        return []
    return [Problem(where(), 1, "the glossary is not what the source would write")]


def main() -> None:
    """Write the glossary, or check it is current and exit."""
    parser = argparse.ArgumentParser(description="write the glossary")
    parser.add_argument("--check", action="store_true", help="only say whether it is current")
    if parser.parse_args().check:
        if is_current():
            print(f"{DOCUMENT} is current")
            sys.exit(0)
        print(f"{DOCUMENT} is not what the source would write")
        sys.exit(1)
    print(f"wrote {write()}")


if __name__ == "__main__":
    main()
