"""Write the command reference out of the console script itself.

Nobody keeps a command reference up to date by hand. This walks the click
tree, prints every group, every command, every argument and every option with
its help, and writes the result into the checkout. CI checks it is current, so
an option added without the document being regenerated fails the build.

The document is the same text ``spikemaul --help`` gives, laid out flat. That
is the point: there is one description of each command and it is the one in
the source.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import click

from spikemaul import __version__
from spikemaul.cli.main import cli
from spikemaul.tools.sources import project_root

DOCUMENT = "docs/commands.md"
"""Where the document lives, relative to the checkout."""


def _parameters(command: click.Command) -> list[str]:
    lines = []
    for parameter in command.params:
        if isinstance(parameter, click.Argument):
            lines.append(f"- `{parameter.name.upper() if parameter.name else ''}`, required")
        elif isinstance(parameter, click.Option):
            flags = ", ".join(f"`{one}`" for one in parameter.opts)
            help_text = parameter.help or ""
            required = ", required" if parameter.required else ""
            lines.append(f"- {flags}{required} {help_text}".rstrip())
    return lines


def _command_lines(path: str, command: click.Command) -> list[str]:
    lines = [f"### {path}", ""]
    if command.help:
        lines.append(command.help.strip().splitlines()[0])
        lines.append("")
    parameters = _parameters(command)
    if parameters:
        lines.extend(parameters)
        lines.append("")
    return lines


def build() -> str:
    """The command reference, as it should be on disk."""
    lines = [
        "# Commands",
        "",
        "Generated by `python -m spikemaul.tools.build_docs`. Do not edit.",
        "",
        f"spikemaul {__version__}",
        "",
    ]
    lines.extend(_parameters(cli))
    lines.append("")
    for name in sorted(cli.commands):
        command = cli.commands[name]
        lines.append(f"## {name}")
        lines.append("")
        if command.help:
            lines.append(command.help.strip().splitlines()[0])
            lines.append("")
        if isinstance(command, click.Group):
            for inner in sorted(command.commands):
                lines.extend(_command_lines(f"{name} {inner}", command.commands[inner]))
        else:
            lines.extend(_parameters(command))
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def where() -> Path:
    """The path the document is written to."""
    return project_root() / DOCUMENT


def write() -> Path:
    """Write the document and say where it went."""
    path = where()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build(), encoding="utf-8")
    return path


def is_current() -> bool:
    """Whether the document on disk is what the script would write."""
    path = where()
    return path.exists() and path.read_text(encoding="utf-8") == build()


def main() -> None:
    """Write the document, or check it is current and exit."""
    parser = argparse.ArgumentParser(description="write the command reference")
    parser.add_argument("--check", action="store_true", help="only say whether it is current")
    if parser.parse_args().check:
        if is_current():
            print(f"{DOCUMENT} is current")
            sys.exit(0)
        print(f"{DOCUMENT} is not what the console script would write")
        sys.exit(1)
    print(f"wrote {write()}")


if __name__ == "__main__":
    main()
